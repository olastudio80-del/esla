-- Служебной роли нужен вход в схему, а не только права на функции.
--
-- В 0001 «grant usage on schema esla» был выдан только authenticated, и
-- всё, что делает сервер, упиралось в «permission denied for schema esla»:
-- подписка через бота, обход молчащих телефонов, обход неотмеченных доз.
-- Снаружи это выглядело исправным — функция ловит ошибку, пишет в лог и
-- возвращает ноль, а HTTP-ответ остаётся 200.
--
-- Отсюда правило: ответ 200 с нулями не доказывает работу. Проверять надо
-- по следу в базе или по логам функции.
--
-- Права на отдельные функции при этом остаются как были: usage на схему
-- не даёт доступа ни к таблицам, ни к функциям, только возможность до них
-- дотянуться.

grant usage on schema esla to service_role;
